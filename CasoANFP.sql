CREATE SEQUENCE SEQ_CLUB START WITH 703 INCREMENT BY 4 NOCACHE NOCYCLE;

-- Periodos [FECHA_INICIO, FECHA_FIN); NULL representa permanencia abierta.
CREATE OR REPLACE TRIGGER TRG_HISTORIAL_NO_SOLAPE
FOR INSERT OR UPDATE OR DELETE ON HISTORIAL_CLUB
COMPOUND TRIGGER
    TYPE T_IDS IS TABLE OF NUMBER INDEX BY VARCHAR2(40);
    G_IDS T_IDS;
    PROCEDURE MARCAR(P_ID NUMBER) IS
        V_ID NUMBER;
    BEGIN
        SELECT ID_INSCRIPCION INTO V_ID FROM JUGADOR
         WHERE ID_INSCRIPCION = P_ID FOR UPDATE;
        G_IDS(TO_CHAR(P_ID)) := P_ID;
    END;
    BEFORE EACH ROW IS
    BEGIN
        IF INSERTING OR UPDATING THEN MARCAR(:NEW.ID_INSCRIPCION); END IF;
        IF DELETING OR UPDATING THEN MARCAR(:OLD.ID_INSCRIPCION); END IF;
    END BEFORE EACH ROW;
    AFTER STATEMENT IS
        V_KEY VARCHAR2(40);
        V_COUNT NUMBER;
    BEGIN
        V_KEY := G_IDS.FIRST;
        WHILE V_KEY IS NOT NULL LOOP
            SELECT COUNT(*) INTO V_COUNT
              FROM HISTORIAL_CLUB A JOIN HISTORIAL_CLUB B
                ON B.ID_INSCRIPCION = A.ID_INSCRIPCION
               AND A.FECHA_INICIO < B.FECHA_INICIO
             WHERE A.ID_INSCRIPCION = G_IDS(V_KEY)
               AND (A.FECHA_FIN IS NULL OR B.FECHA_INICIO < A.FECHA_FIN);
            IF V_COUNT > 0 THEN
                RAISE_APPLICATION_ERROR(-20001, 'El jugador tiene periodos de club superpuestos');
            END IF;
            V_KEY := G_IDS.NEXT(V_KEY);
        END LOOP;
    END AFTER STATEMENT;
END TRG_HISTORIAL_NO_SOLAPE;

SET DEFINE OFF

-- Esperado: 7 regiones, 5 comunas, 10 asociaciones, 5 nacionalidades, 5 clubes.
SELECT 'REGION' AS TABLA, COUNT(*) AS FILAS FROM REGION
UNION ALL SELECT 'COMUNA', COUNT(*) FROM COMUNA
UNION ALL SELECT 'ASOCIACION', COUNT(*) FROM ASOCIACION
UNION ALL SELECT 'NACIONALIDAD', COUNT(*) FROM NACIONALIDAD
UNION ALL SELECT 'CLUB_FUTBOL', COUNT(*) FROM CLUB_FUTBOL;

-- Esperado: 210, 212, 214, 216, 218.
SELECT ID_NACION, DESCRIPCION FROM NACIONALIDAD ORDER BY ID_NACION;
-- Esperado: 703, 707, 711, 715, 719.
SELECT ID_CLUB, NOMBRE_CLUB FROM CLUB_FUTBOL ORDER BY ID_CLUB;

-- Esperado: ninguna fila (referencias huerfanas).
SELECT C.ID_COMUNA, C.ID_REGION
FROM COMUNA C LEFT JOIN REGION R ON R.ID_REGION = C.ID_REGION
WHERE R.ID_REGION IS NULL;

-- Esperado: todas las restricciones ENABLED y VALIDATED.
SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE, STATUS, VALIDATED
FROM USER_CONSTRAINTS
WHERE TABLE_NAME IN ('REGION','COMUNA','ASOCIACION','NACIONALIDAD',
 'CLUB_FUTBOL','ESCUELA_FUTBOL','IDIOMA','TRABAJADOR','JUGADOR',
 'PERSONAL_PLANTA','HISTORIAL_CLUB','JUGADOR_IDIOMA')
ORDER BY TABLE_NAME, CONSTRAINT_TYPE, CONSTRAINT_NAME;

-- Esperado: ALWAYS, START WITH 210, INCREMENT BY 2.
SELECT TABLE_NAME, COLUMN_NAME, GENERATION_TYPE, IDENTITY_OPTIONS
FROM USER_TAB_IDENTITY_COLS WHERE TABLE_NAME = 'NACIONALIDAD';
-- Esperado: INCREMENT_BY = 4. LAST_NUMBER no consume la secuencia.
SELECT SEQUENCE_NAME, INCREMENT_BY, CYCLE_FLAG, CACHE_SIZE, LAST_NUMBER
FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_CLUB';

-- Esperado: VALID y ninguna fila en USER_ERRORS.
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS
WHERE OBJECT_NAME = 'TRG_HISTORIAL_NO_SOLAPE';
SELECT NAME, TYPE, LINE, POSITION, TEXT FROM USER_ERRORS
WHERE NAME = 'TRG_HISTORIAL_NO_SOLAPE' ORDER BY SEQUENCE;

-- Esperado: cero; tambien comprueba la participacion total al cargar trabajadores.
SELECT T.ID_INSCRIPCION, T.TIPO_TRABAJADOR
FROM TRABAJADOR T
LEFT JOIN JUGADOR J ON J.ID_INSCRIPCION = T.ID_INSCRIPCION
LEFT JOIN PERSONAL_PLANTA P ON P.ID_INSCRIPCION = T.ID_INSCRIPCION
WHERE (T.TIPO_TRABAJADOR = 'J' AND J.ID_INSCRIPCION IS NULL)
   OR (T.TIPO_TRABAJADOR = 'P' AND P.ID_INSCRIPCION IS NULL);
